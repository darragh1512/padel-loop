-- BASELINE SNAPSHOT of the already-live match-results schema + RLS.
-- These tables EXIST in production. Do NOT run this against prod — it is a
-- source-of-truth artifact for version control and fresh-env reproduction
-- (e.g. a Supabase branch). Captured 2026-06-25 via information_schema/pg_policies.

create table if not exists public.match_results (
  id           bigint generated by default as identity primary key, -- VERIFY: assumed identity (live column_default was null)
  game_id      bigint not null unique references public.games (id) on delete cascade,
  submitted_by uuid   not null,            -- NB: no FK in live DB; references auth.users.id by convention only
  status       text   not null default 'pending',
  winning_team smallint,
  created_at   timestamptz not null default now(),
  confirmed_at timestamptz
);

create table if not exists public.match_result_participants (
  result_id    bigint   not null references public.match_results (id) on delete cascade,
  user_id      uuid     not null,
  team         smallint not null,
  confirmation text     not null default 'pending',
  created_at   timestamptz not null default now(),
  primary key (result_id, user_id)
);

create table if not exists public.match_result_sets (
  result_id   bigint   not null references public.match_results (id) on delete cascade,
  set_number  smallint not null,
  team1_games smallint not null,
  team2_games smallint not null,
  primary key (result_id, set_number)
);

alter table public.match_results             enable row level security;
alter table public.match_result_participants enable row level security;
alter table public.match_result_sets         enable row level security;

-- match_results
create policy "Results readable by authenticated"
  on public.match_results for select to authenticated using (true);

create policy "Game members can submit a result"
  on public.match_results for insert to authenticated
  with check (
    submitted_by = auth.uid()
    and exists (select 1 from public.game_players gp
                where gp.game_id = match_results.game_id and gp.user_id = auth.uid())
  );

create policy "Game members can update the result"
  on public.match_results for update to authenticated
  using (
    exists (select 1 from public.game_players gp
            where gp.game_id = match_results.game_id and gp.user_id = auth.uid())
  );
-- ^^^ SECURITY HOLE: WITH CHECK falls back to the USING (game-membership) test only.
--     It does NOT restrict which columns change, so any member can set
--     status / winning_team / confirmed_at unilaterally. Replaced in the next step.

-- match_result_participants
create policy "Participants readable by authenticated"
  on public.match_result_participants for select to authenticated using (true);

create policy "Submitter creates participant rows"
  on public.match_result_participants for insert to authenticated
  with check (
    exists (select 1 from public.match_results r
            where r.id = match_result_participants.result_id and r.submitted_by = auth.uid())
  );

create policy "Users update their own confirmation"
  on public.match_result_participants for update to authenticated
  using (user_id = auth.uid());
-- NB: no WITH CHECK → a confirming user could also change their own `team`. Tighten in harden step.

-- match_result_sets
create policy "Sets readable by authenticated"
  on public.match_result_sets for select to authenticated using (true);

create policy "Submitter writes sets"
  on public.match_result_sets for insert to authenticated
  with check (
    exists (select 1 from public.match_results r
            where r.id = match_result_sets.result_id and r.submitted_by = auth.uid())
  );

create policy "Submitter updates sets"
  on public.match_result_sets for update to authenticated
  using (
    exists (select 1 from public.match_results r
            where r.id = match_result_sets.result_id and r.submitted_by = auth.uid())
  );

create policy "Submitter deletes sets"
  on public.match_result_sets for delete to authenticated
  using (
    exists (select 1 from public.match_results r
            where r.id = match_result_sets.result_id and r.submitted_by = auth.uid())
  );
